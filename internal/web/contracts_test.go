package web

// Generate only explicitly browser-safe projections. Raw client/context types
// contain capabilities and must never be roots of this schema.
import (
	"encoding/json"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
	"testing"
	"time"
	"unicode"

	"github.com/merefield/codexometer/internal/codex"
	"github.com/merefield/codexometer/internal/quotagraph"
)

func browserContract() string {
	names := map[reflect.Type]string{
		reflect.TypeFor[state](): "Snapshot", reflect.TypeFor[session](): "Session",
		reflect.TypeFor[goal](): "SessionGoal", reflect.TypeFor[meter](): "Meter",
		reflect.TypeFor[credit](): "Credit", reflect.TypeFor[sample](): "Sample",
		reflect.TypeFor[codex.AccountUsage](): "Usage", reflect.TypeFor[quotaThreshold](): "Threshold",
		reflect.TypeFor[commandMenu](): "CommandMenu", reflect.TypeFor[codex.SessionCommandChoice](): "CommandChoice",
		reflect.TypeFor[actionOffer](): "ActionOffer", reflect.TypeFor[scheduledJob](): "ScheduledJob",
		reflect.TypeFor[quotagraph.Plot](): "QuotaPlot",
	}
	definitions := map[string]string{}
	var value func(reflect.Type, bool) string
	var fields func(reflect.Type) string
	fields = func(typ reflect.Type) (out string) {
		for i := 0; i < typ.NumField(); i++ {
			f := typ.Field(i)
			if f.PkgPath != "" {
				continue
			}
			if f.Anonymous {
				out += fields(f.Type)
				continue
			}
			tag, options, _ := strings.Cut(f.Tag.Get("json"), ",")
			if tag == "-" {
				continue
			}
			if tag == "" {
				tag = f.Name
			}
			optional := ""
			if strings.Contains(options, "omitempty") {
				optional = "?"
			}
			out += fmt.Sprintf("  %s%s: %s;\n", tag, optional, value(f.Type, f.Tag.Get("ts") == "nonnull"))
		}
		return out
	}
	value = func(typ reflect.Type, nonnull bool) string {
		if typ == reflect.TypeFor[time.Time]() {
			return "string"
		}
		switch typ.Kind() {
		case reflect.Pointer:
			return value(typ.Elem(), false) + " | null"
		case reflect.Slice:
			out := "Array<" + value(typ.Elem(), false) + ">"
			if !nonnull {
				out += " | null"
			}
			return out
		case reflect.Array:
			return "Array<" + value(typ.Elem(), false) + ">"
		case reflect.Map:
			return "Record<string, " + value(typ.Elem(), false) + ">"
		case reflect.Struct:
			name := names[typ]
			if name == "" {
				runes := []rune(typ.Name())
				runes[0] = unicode.ToUpper(runes[0])
				name = string(runes)
				names[typ] = name
			}
			if _, seen := definitions[name]; !seen {
				definitions[name] = ""
				definitions[name] = "export interface " + name + " {\n" + fields(typ) + "}\n"
			}
			return name
		case reflect.Bool:
			return "boolean"
		case reflect.String:
			return "string"
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
			return "number"
		default:
			panic("unsupported browser contract: " + typ.String())
		}
	}
	for _, typ := range []reflect.Type{reflect.TypeFor[state](), reflect.TypeFor[commandMenu](), reflect.TypeFor[actionOffer](), reflect.TypeFor[scheduledJob]()} {
		value(typ, false)
	}
	ordered := make([]string, 0, len(definitions))
	for name := range definitions {
		ordered = append(ordered, name)
	}
	sort.Strings(ordered)
	out := "// Code generated by make web-contracts; DO NOT EDIT.\n\n"
	for _, name := range ordered {
		out += definitions[name] + "\n"
	}
	commands, _ := json.MarshalIndent(codex.LocalSessionCommands(), "", "  ")
	return out + "export const localCommands: CommandChoice[] = " + string(commands) + ";\n"
}

func TestBrowserContract(t *testing.T) {
	const path = "../../web/src/contracts.generated.ts"
	want := browserContract()
	if os.Getenv("CODEXOMETER_WEB_GENERATE") == "1" {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != want {
		t.Fatal("browser contract is stale; run make web-contracts", err)
	}
	for _, secret := range []string{"approvalToken:", "accountFingerprint:", "token:", "params:", "account:"} {
		if strings.Contains(want, secret) {
			t.Fatal("internal capability leaked into browser contract", secret)
		}
	}
}
